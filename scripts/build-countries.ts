/**
 * Generates `src/data/countries.ts` (SPEC §14.4): `{ ISO2: [lng, lat, zoom] }`
 * for every country in world-atlas 50m (the 110m set lacks Singapore, Hong
 * Kong and other small places a trip visits). The point is the country's
 * `d3-geo` `geoCentroid`; the zoom fits its bounds. A few countries whose
 * geometry pulls the centroid away (overseas territories, Alaska, Svalbard)
 * and the trip's own countries (JP, KR, VN, TW) are set by hand.
 *
 *   N pnpm countries      # rewrites src/data/countries.ts (checked in)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoBounds, geoCentroid } from "d3-geo";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";

const require = createRequire(import.meta.url);
const atlas = JSON.parse(
	readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"),
) as Topology<{ countries: GeometryCollection<{ name: string }> }>;

